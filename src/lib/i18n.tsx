export const DICTS: Record<Lang, Dict> = { en, hi, mr }

/** Payment reminder text. Polite, relationship-first wording in every language. */
export function reminderText(lang: Lang, o: { name: string; shop: string; shopLocal: string; amount: string; link?: string }) {
  const first = o.name.split(' ')[0]
  const link = o.link ? (lang === 'en' ? `\n\nPay by UPI: ${o.link}` : lang === 'hi' ? `\n\nUPI से भुगतान: ${o.link}` : `\n\nUPI ने भरणा: ${o.link}`) : ''
  if (lang === 'hi')
    return `नमस्ते ${first} जी,\n${o.shopLocal} में आपका ${o.amount} बाकी है। जब सुविधा हो, तब चुका दीजिए।\nधन्यवाद 🙏${link}`
  if (lang === 'mr')
    return `नमस्कार ${first} जी,\n${o.shopLocal} येथे तुमची ${o.amount} बाकी आहे. सोयीनुसार भरावी ही विनंती.\nधन्यवाद 🙏${link}`
  return `Namaste ${first} ji,\nYour balance at ${o.shop} is ${o.amount}. Please pay whenever convenient.\nThank you 🙏${link}`
}

interface I18nCtx {
  lang: Lang
  t: Dict
  setLang: (l: Lang) => void
}
const Ctx = createContext<I18nCtx | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => (localStorage.getItem('bahi.lang') as Lang) || 'en')
  useEffect(() => {
    localStorage.setItem('bahi.lang', lang)
    document.documentElement.lang = lang
  }, [lang])
  return <Ctx.Provider value={{ lang, t: DICTS[lang], setLang }}>{children}</Ctx.Provider>
}

// eslint-disable-next-line react-refresh/only-export-components
export function useT() {
  const v = useContext(Ctx)
  if (!v) throw new Error('useT outside I18nProvider')
  return v
}
