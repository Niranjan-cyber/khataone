import { chromium, devices } from '@playwright/test'
const out = process.argv[2], base = 'http://localhost:5173'
const b = await chromium.launch()
const ctx = await b.newContext({ ...devices['Pixel 7'], viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, reducedMotion: 'reduce' })
const p = await ctx.newPage()
await p.goto(base); await p.evaluate(() => { localStorage.clear(); localStorage.setItem('khataone.lang', 'en') })
const shot = async (hash, name, fn) => { await p.goto(base + '/' + hash); await p.reload(); await p.waitForTimeout(500); if (fn) await fn(); await p.waitForTimeout(350); await p.screenshot({ path: `${out}/${name}.png` }) }
const keys = async (s) => { for (const k of s) await p.locator('.key', { hasText: new RegExp(`^${k}$`) }).click() }
await shot('#/', '1-home')
await shot('#/pick/udhaar', '2-pick')
await shot('#/entry/udhaar/c1', '3-entry', () => keys('250'))
await shot('#/ledger/c1', '4-ledger')
await shot('#/remind/c1', '5-remind')
await shot('#/collect/c1', '6-collect')
await shot('#/collect/c1', '6b-collect-failed', () => p.getByRole('button', { name: 'Fail' }).click())
await shot('#/entry/udhaar/c1', '3b-saved', async () => { await keys('250'); await p.getByTestId('save').click() })
await shot('#/ledger/c1', '4b-cancel-sheet', () => p.locator('.lrow').first().click())
await p.evaluate(() => localStorage.setItem('khataone.lang', 'hi'))
await shot('#/', '1-home-hi')
await shot('#/entry/udhaar/c2', '3-entry-hi', () => keys('137'))
await p.evaluate(() => localStorage.setItem('khataone.lang', 'mr'))
await shot('#/ledger/c3', '4-ledger-mr')
await p.setViewportSize({ width: 320, height: 640 })
await p.evaluate(() => localStorage.setItem('khataone.lang', 'en'))
await shot('#/', 'w320-home'); await shot('#/entry/udhaar/c1', 'w320-entry', () => keys('99999'))
await b.close()
